begin;

create table if not exists public.wedding_esenciales (
  id bigint generated by default as identity primary key,
  categoria text not null,
  titulo text not null,
  estado text not null default 'por_definir' check (estado in ('por_definir','buscando','elegido','contratado','listo','no_aplica')),
  notas text,
  orden integer not null default 0,
  fecha_actualizacion timestamptz not null default now(),
  unique (categoria, titulo)
);

alter table public.wedding_esenciales enable row level security;
revoke all on table public.wedding_esenciales from anon, authenticated;

