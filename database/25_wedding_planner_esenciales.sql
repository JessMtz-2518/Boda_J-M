create or replace function public.admin_esenciales_resumen()
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_data jsonb;
begin
 if v_uid is null or not public.es_admin_activo(v_uid) then raise exception 'acceso_administrativo_no_autorizado'; end if;
 select jsonb_build_object(
  'schema_version','1.0','generated_at',now(),
  'data',jsonb_build_object(
   'resumen',jsonb_build_object(
    'total',count(*) filter(where estado<>'no_aplica'),
    'listos',count(*) filter(where estado='listo'),
    'contratados',count(*) filter(where estado='contratado'),
    'en_decision',count(*) filter(where estado in ('buscando','elegido')),
    'por_definir',count(*) filter(where estado='por_definir'),
    'porcentaje',case when count(*) filter(where estado<>'no_aplica')=0 then 0 else round(100.0*count(*) filter(where estado in ('listo','contratado'))/count(*) filter(where estado<>'no_aplica')) end
   ),
   'items',coalesce(jsonb_agg(jsonb_build_object('id',id,'categoria',categoria,'titulo',titulo,'estado',estado,'notas',notas,'orden',orden,'fecha_actualizacion',fecha_actualizacion) order by categoria,orden,titulo),'[]'::jsonb)
  )) into v_data from public.wedding_esenciales;
 return v_data;
end $$;

create or replace function public.admin_esenciales_actualizar(p_id bigint,p_estado text,p_notas text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null or not public.es_admin_activo(auth.uid()) then raise exception 'acceso_administrativo_no_autorizado'; end if;
 if p_estado not in ('por_definir','buscando','elegido','contratado','listo','no_aplica') then raise exception 'estado_invalido'; end if;
 update public.wedding_esenciales set estado=p_estado,notas=nullif(trim(coalesce(p_notas,'')),''),fecha_actualizacion=now() where id=p_id;
 if not found then raise exception 'esencial_no_encontrado'; end if;
 return jsonb_build_object('schema_version','1.0','generated_at',now(),'data',jsonb_build_object('ok',true,'id',p_id));
end $$;

revoke execute on function public.admin_esenciales_resumen() from public, anon;
revoke execute on function public.admin_esenciales_actualizar(bigint,text,text) from public, anon;
grant execute on function public.admin_esenciales_resumen() to authenticated;
grant execute on function public.admin_esenciales_actualizar(bigint,text,text) to authenticated;
commit;
