-- =========================================================
-- 4. AMPLIAR ACCIONES DE HISTORIAL
-- =========================================================

do $$
declare
    v_constraint text;
begin
    select c.conname
    into v_constraint
    from pg_constraint as c
    where c.conrelid = 'public.historial_mesas'::regclass
      and c.contype = 'c'
      and pg_get_constraintdef(c.oid) ilike '%accion%'
    limit 1;

    if v_constraint is not null then
        execute format(
            'alter table public.historial_mesas drop constraint %I',
            v_constraint
        );
    end if;

    alter table public.historial_mesas
        add constraint historial_mesas_accion_check
        check (
            accion in (
                'configuracion_inicial',
                'reconfigurado',
                'mesa_creada',
                'mesa_actualizada',
                'mesa_desactivada',
                'mesa_reactivada',
                'asignado',
                'reasignado',
                'asignacion_retirada',
                'sincronizado_confirmacion',
                'asignaciones_liberadas',
                'plano_actualizado',
                'elementos_plano_actualizados'
            )
        );
exception
    when duplicate_object then
        null;
end;
$$;


-- =========================================================
-- 5. LISTAR ELEMENTOS
-- =========================================================

create or replace function public.admin_listar_elementos_plano()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_items jsonb;
begin
    if auth.uid() is null
       or not private.es_administrador_activo() then
        raise exception 'Acceso administrativo no autorizado.'
            using errcode = '42501';
    end if;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', e.id,
                'tipo', e.tipo,
                'nombre', e.nombre,
                'plano_x', e.plano_x,
                'plano_y', e.plano_y,
                'ancho', e.ancho,
                'alto', e.alto,
                'activo', e.activo,
                'version', e.fecha_actualizacion
            )
            order by e.id
        ),
        '[]'::jsonb
    )
    into v_items
    from public.elementos_plano as e
    where e.activo = true;

    return jsonb_build_object(
        'schema_version', '1.0',
        'generated_at', now(),
        'data', jsonb_build_object(
            'items', v_items
        )
    );
end;
$$;


-- =========================================================
-- 6. GUARDAR ELEMENTOS
-- =========================================================

create or replace function public.admin_guardar_elementos_plano(
    p_elementos jsonb,
    p_motivo text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
    v_usuario_id uuid := auth.uid();
    v_admin_nombre text;
    v_motivo text := trim(coalesce(p_motivo, ''));

    v_item jsonb;
    v_id bigint;
    v_x numeric;
    v_y numeric;
    v_ancho numeric;
    v_alto numeric;

    v_anteriores jsonb;
    v_nuevos jsonb;
    v_total integer := 0;
begin
    if v_usuario_id is null
       or not private.es_administrador_activo() then
        raise exception 'Acceso administrativo no autorizado.'
            using errcode = '42501';
    end if;

    if p_elementos is null
       or jsonb_typeof(p_elementos) <> 'array'
       or jsonb_array_length(p_elementos) = 0 then
        raise exception 'ELEMENTOS_PLANO_INVALIDOS'
            using errcode = '22023';
    end if;

    if char_length(v_motivo) not between 1 and 1000 then
        raise exception 'MOTIVO_INVALIDO'
            using errcode = '22023';
    end if;

    select a.nombre
    into v_admin_nombre
    from public.administradores as a
    where a.usuario_id = v_usuario_id
      and a.activo = true
      and a.rol = 'administrador';

    if v_admin_nombre is null then
        raise exception 'Acceso administrativo no autorizado.'
            using errcode = '42501';
    end if;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', e.id,
                'tipo', e.tipo,
                'nombre', e.nombre,
                'x', e.plano_x,
                'y', e.plano_y,
                'ancho', e.ancho,
                'alto', e.alto
            )
            order by e.id
        ),
        '[]'::jsonb
    )
    into v_anteriores
    from public.elementos_plano as e
    where e.activo = true
      and e.id in (
          select (x ->> 'id')::bigint
          from jsonb_array_elements(p_elementos) as x
      );

    for v_item in
        select value
        from jsonb_array_elements(p_elementos)
    loop
        v_id := nullif(v_item ->> 'id', '')::bigint;
        v_x := nullif(v_item ->> 'x', '')::numeric;
        v_y := nullif(v_item ->> 'y', '')::numeric;
        v_ancho := nullif(v_item ->> 'ancho', '')::numeric;
        v_alto := nullif(v_item ->> 'alto', '')::numeric;

        if v_id is null
           or v_x is null
           or v_y is null
           or v_ancho is null
           or v_alto is null
           or v_x not between 0 and 100
           or v_y not between 0 and 100
           or v_ancho not between 3 and 80
           or v_alto not between 3 and 80 then
            raise exception 'ELEMENTO_PLANO_POSICION_INVALIDA'
                using errcode = '22023';
        end if;

        update public.elementos_plano
        set
            plano_x = round(v_x, 3),
            plano_y = round(v_y, 3),
            ancho = round(v_ancho, 3),
            alto = round(v_alto, 3)
        where id = v_id
          and activo = true;

        if not found then
            raise exception 'ELEMENTO_PLANO_NO_ENCONTRADO'
                using errcode = 'P0002';
        end if;

        v_total := v_total + 1;
    end loop;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', e.id,
                'tipo', e.tipo,
                'nombre', e.nombre,
                'x', e.plano_x,
                'y', e.plano_y,
                'ancho', e.ancho,
                'alto', e.alto
            )
            order by e.id
        ),
        '[]'::jsonb
    )
    into v_nuevos
    from public.elementos_plano as e
    where e.activo = true
      and e.id in (
          select (x ->> 'id')::bigint
          from jsonb_array_elements(p_elementos) as x
      );

    insert into public.historial_mesas (
        tipo_entidad,
        entidad_id,
        accion,
        datos_anteriores,
        datos_nuevos,
        modificado_por,
        administrador_nombre,
        motivo
    )
    values (
        'configuracion',
        null,
        'elementos_plano_actualizados',
        jsonb_build_object('elementos', v_anteriores),
        jsonb_build_object('elementos', v_nuevos),
        v_usuario_id,
        v_admin_nombre,
        v_motivo
    );

    return jsonb_build_object(
        'schema_version', '1.0',
        'generated_at', now(),
        'data', jsonb_build_object(
            'saved', true,
            'elementos_actualizados', v_total
        )
    );
end;
$$;


