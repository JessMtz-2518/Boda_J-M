-- =========================================================
-- 1. TABLA DE ELEMENTOS DEL PLANO
-- =========================================================

create table if not exists public.elementos_plano (
    id bigint generated by default as identity primary key,
    tipo text not null,
    nombre text not null,
    plano_x numeric(6,3),
    plano_y numeric(6,3),
    ancho numeric(6,3) not null default 18,
    alto numeric(6,3) not null default 12,
    activo boolean not null default true,
    fecha_creacion timestamptz not null default now(),
    fecha_actualizacion timestamptz not null default now(),

    constraint elementos_plano_tipo_check
        check (
            tipo in (
                'mesa_novios',
                'pista_baile',
                'mesa_pastel',
                'dj',
                'barra',
                'entrada',
                'escenario',
                'otro'
            )
        ),

    constraint elementos_plano_x_check
        check (plano_x is null or plano_x between 0 and 100),

    constraint elementos_plano_y_check
        check (plano_y is null or plano_y between 0 and 100),

    constraint elementos_plano_ancho_check
        check (ancho between 3 and 80),

    constraint elementos_plano_alto_check
        check (alto between 3 and 80)
);

create unique index if not exists elementos_plano_tipo_unico_activo
on public.elementos_plano(tipo)
where activo = true
  and tipo in ('mesa_novios', 'pista_baile');


-- =========================================================
-- 2. TRIGGER DE FECHA
-- =========================================================

create or replace function public.actualizar_fecha_elementos_plano()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.fecha_actualizacion := now();
    return new;
end;
$$;

drop trigger if exists trg_elementos_plano_fecha
on public.elementos_plano;

create trigger trg_elementos_plano_fecha
before update on public.elementos_plano
for each row
execute function public.actualizar_fecha_elementos_plano();


